package dev.abgleich.adapter.out.synthetic;

import dev.abgleich.domain.account.Iban;
import dev.abgleich.domain.money.Money;
import java.nio.charset.StandardCharsets;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

/** Writes camt.053.001.04 statements with balances that always add up. */
final class CamtWriter {

    private final String messageId;
    private final LocalDate day;
    private final List<Statement> statements = new ArrayList<>();

    CamtWriter(String messageId, LocalDate day) {
        this.messageId = messageId;
        this.day = day;
    }

    Statement statement(String id, Iban account, Money opening) {
        Statement statement = new Statement(id, account, opening);
        statements.add(statement);
        return statement;
    }

    byte[] toBytes() {
        StringBuilder xml = new StringBuilder()
                .append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
                .append("<!-- Synthetic data generated by Abgleich: every name, IBAN and reference is invented. -->\n")
                .append("<Document xmlns=\"urn:iso:std:iso:20022:tech:xsd:camt.053.001.04\">\n")
                .append("  <BkToCstmrStmt>\n")
                .append("    <GrpHdr><MsgId>").append(escape(messageId)).append("</MsgId>")
                .append("<CreDtTm>").append(day).append("T22:00:00+02:00</CreDtTm></GrpHdr>\n");
        statements.forEach(statement -> statement.appendTo(xml));
        return xml.append("  </BkToCstmrStmt>\n</Document>\n").toString().getBytes(StandardCharsets.UTF_8);
    }

    final class Statement {
        private final String id;
        private final Iban account;
        private final Money opening;
        private Money closing;
        private final StringBuilder entries = new StringBuilder();

        private Statement(String id, Iban account, Money opening) {
            this.id = id;
            this.account = account;
            this.opening = opening;
            this.closing = opening;
        }

        Statement credit(String bankReference, Payment payment) {
            return entry(bankReference, payment.amount(), "CRDT", List.of(payment), null);
        }

        /** One booking for several payments (B09): the entry amount is the sum of its transactions. */
        Statement batchCredit(String bankReference, List<Payment> payments) {
            Money total = payments.stream().map(Payment::amount).reduce(Money::add).orElseThrow();
            return entry(bankReference, total, "CRDT", payments, null);
        }

        Statement debit(String bankReference, Money amount, String information) {
            return entry(bankReference, amount, "DBIT", List.of(), information);
        }

        private Statement entry(String bankReference, Money amount, String indicator, List<Payment> payments,
                String information) {
            closing = indicator.equals("CRDT") ? closing.add(amount) : closing.subtract(amount);
            entries.append("      <Ntry>\n")
                    .append("        ").append(amount(amount)).append("\n")
                    .append("        <CdtDbtInd>").append(indicator).append("</CdtDbtInd>\n")
                    .append("        <Sts>BOOK</Sts>\n")
                    .append("        <BookgDt><Dt>").append(day).append("</Dt></BookgDt>\n")
                    .append("        <ValDt><Dt>").append(day).append("</Dt></ValDt>\n")
                    .append("        <AcctSvcrRef>").append(escape(bankReference)).append("</AcctSvcrRef>\n")
                    .append("        <BkTxCd><Domn><Cd>PMNT</Cd><Fmly><Cd>")
                    .append(indicator.equals("CRDT") ? "RCDT" : "ICDT")
                    .append("</Cd><SubFmlyCd>AUTT</SubFmlyCd></Fmly></Domn></BkTxCd>\n");
            if (!payments.isEmpty()) {
                entries.append("        <NtryDtls>\n");
                if (payments.size() > 1) {
                    entries.append("          <Btch><NbOfTxs>").append(payments.size()).append("</NbOfTxs></Btch>\n");
                }
                for (int i = 0; i < payments.size(); i++) {
                    appendTransaction(bankReference + "-" + (i + 1), payments.get(i));
                }
                entries.append("        </NtryDtls>\n");
            }
            if (information != null) {
                entries.append("        <AddtlNtryInf>").append(escape(information)).append("</AddtlNtryInf>\n");
            }
            entries.append("      </Ntry>\n");
            return this;
        }

        private void appendTransaction(String reference, Payment payment) {
            entries.append("          <TxDtls>\n")
                    .append("            <Refs><AcctSvcrRef>").append(escape(reference)).append("</AcctSvcrRef></Refs>\n")
                    .append("            <AmtDtls><TxAmt>").append(amount(payment.amount())).append("</TxAmt></AmtDtls>\n")
                    .append("            <RltdPties><Dbtr><Nm>").append(escape(payment.payer())).append("</Nm></Dbtr></RltdPties>\n");
            if (payment.structuredReference() != null || payment.remittance() != null) {
                entries.append("            <RmtInf>\n");
                if (payment.remittance() != null) {
                    entries.append("              <Ustrd>").append(escape(payment.remittance())).append("</Ustrd>\n");
                }
                if (payment.structuredReference() != null) {
                    String type = payment.structuredReference().startsWith("RF")
                            ? "<Cd>SCOR</Cd>"
                            : "<Prtry>QRR</Prtry>";
                    entries.append("              <Strd><CdtrRefInf><Tp><CdOrPrtry>").append(type)
                            .append("</CdOrPrtry></Tp><Ref>").append(escape(payment.structuredReference()))
                            .append("</Ref></CdtrRefInf></Strd>\n");
                }
                entries.append("            </RmtInf>\n");
            }
            entries.append("          </TxDtls>\n");
        }

        private void appendTo(StringBuilder xml) {
            xml.append("    <Stmt>\n")
                    .append("      <Id>").append(escape(id)).append("</Id>\n")
                    .append("      <CreDtTm>").append(day).append("T22:00:00+02:00</CreDtTm>\n")
                    .append("      <Acct><Id><IBAN>").append(account.value()).append("</IBAN></Id>")
                    .append("<Ccy>").append(opening.currency().getCurrencyCode()).append("</Ccy></Acct>\n")
                    .append(balance("OPBD", opening, day.minusDays(1)))
                    .append(balance("CLBD", closing, day))
                    .append(entries)
                    .append("    </Stmt>\n");
        }

        private String balance(String type, Money amount, LocalDate date) {
            return "      <Bal><Tp><CdOrPrtry><Cd>" + type + "</Cd></CdOrPrtry></Tp>"
                    + amount(amount.isNegative() ? Money.zero(amount.currency()).subtract(amount) : amount)
                    + "<CdtDbtInd>" + (amount.isNegative() ? "DBIT" : "CRDT") + "</CdtDbtInd>"
                    + "<Dt><Dt>" + date + "</Dt></Dt></Bal>\n";
        }
    }

    private static String amount(Money money) {
        return "<Amt Ccy=\"" + money.currency().getCurrencyCode() + "\">" + money.amount().toPlainString() + "</Amt>";
    }

    private static String escape(String text) {
        return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }
}
